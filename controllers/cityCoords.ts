// ── Lookup helpers ─────────────────────────────────────────────────────────

/** Normalize a city name to the canonical lookup key */
function normalise(city: string): string {
  return city
    .toLowerCase()
    .trim()
    .replace(/\s*\(.*\)/, "") // strip "(DC)" suffixes
    .trim();
}

/**
 * Synchronous city lookup from static table.
 * Returns [lat, lng] or null if not found.
 */
export function getCityCoords(city: string): LatLng | null {
  if (!city || city === "(not set)") return null;
  const key = normalise(city);
  return CITY_COORDS[key] ?? null;
}

/**
 * Async city lookup that falls back to the country's capital coordinates
 * (from the bundled country list) when the city is not in the static table.
 *
 * @param city     City name as returned by GA4 (e.g. "Hyderabad")
 * @param countryId  ISO 3166-1 alpha-2 country code (e.g. "IN")
 */
export async function getCityCoordsWithFallback(
  city: string,
  countryId: string
): Promise<LatLng | null> {
  const fast = getCityCoords(city);
  if (fast) return fast;

  // Fallback: country capital from restcountries.com cache
  try {
    const capitalCoords = await getCapitalLatLng(countryId);
    return capitalCoords;
  } catch {
    return null;
  }
}
